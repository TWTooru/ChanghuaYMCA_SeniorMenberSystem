declare
  sequence_name text;
  sequence_last bigint;
begin
  sequence_name := pg_catalog.pg_get_serial_sequence(
    'public.students', 'student_id'
  );
  if new.student_id is not null and sequence_name is not null then
    execute pg_catalog.format('select last_value from %s', sequence_name)
      into sequence_last;
    if new.student_id > sequence_last then
      perform pg_catalog.setval(sequence_name::pg_catalog.regclass, new.student_id, true);
    end if;
  end if;
  return new;
end
