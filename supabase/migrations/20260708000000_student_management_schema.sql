create table public.students (
  student_id text primary key,
  original_id text,
  name text not null,
  gender text,
  birth_date date,
  age integer check (age is null or age >= 0),
  is_60_plus text,
  address text,
  home_phone text,
  mobile_phone text,
  emergency_contact text,
  relationship text,
  emergency_contact_phone text,
  education text,
  occupation text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.enrollments (
  enrollment_id bigint generated by default as identity primary key,
  student_id text not null references public.students(student_id) on delete cascade,
  season text not null,
  reg_type text,
  pre_test text,
  post_test text,
  refunded integer not null default 0 check (refunded in (0, 1)),
  refund_info text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (student_id, season)
);

create table public.courses (
  course_id bigint generated by default as identity primary key,
  enrollment_id bigint not null references public.enrollments(enrollment_id) on delete cascade,
  course_name text not null,
  created_at timestamptz not null default now(),
  unique (enrollment_id, course_name)
);

create index students_name_idx on public.students (name);
create index enrollments_student_id_idx on public.enrollments (student_id);
create index enrollments_season_idx on public.enrollments (season);
create index courses_enrollment_id_idx on public.courses (enrollment_id);
create index courses_course_name_idx on public.courses (course_name);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger students_set_updated_at
before update on public.students
for each row execute function public.set_updated_at();

create trigger enrollments_set_updated_at
before update on public.enrollments
for each row execute function public.set_updated_at();

