create table public.course_catalog (
  course_catalog_id bigint generated by default as identity primary key,
  course_name text not null check (btrim(course_name) <> ''),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index course_catalog_normalized_name_uidx
on public.course_catalog ((lower(btrim(course_name))));

create table public.course_receipts (
  receipt_id bigint generated by default as identity primary key,
  course_id bigint not null unique
    references public.courses(course_id) on delete cascade,
  amount integer check (amount is null or amount >= 0),
  invoice_number text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- The initial schema owns this helper, but production installations may have
-- lost it outside migration history. Keep this migration self-contained.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger course_catalog_set_updated_at
before update on public.course_catalog
for each row execute function public.set_updated_at();

create trigger course_receipts_set_updated_at
before update on public.course_receipts
for each row execute function public.set_updated_at();

