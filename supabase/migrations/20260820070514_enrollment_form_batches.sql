create or replace function public.create_enrollment_with_courses(
  p_student_id bigint,
  p_period text,
  p_reg_type text,
  p_refunded integer,
  p_refund_info text,
  p_course_names text[],
  p_payment_records jsonb default '[]'::jsonb
) returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_enrollment_id bigint;
  v_form_id bigint;
  v_names text[];
  v_payment jsonb;
  v_course text;
  v_amount integer;
  v_receipt bigint;
begin
  if public.current_app_role() not in ('editor','admin') then
    raise exception 'ENROLLMENT_CREATE_FORBIDDEN' using errcode='42501';
  end if;
  if p_period !~ '^第[1-9][0-9]*期$' then
    raise exception 'PERIOD_INVALID';
  end if;
  if not exists (select 1 from public.students s where s.student_id = p_student_id) then
    raise exception 'STUDENT_NOT_FOUND';
  end if;
  select array_agg(name order by name) into v_names
  from (
    select min(btrim(x)) name
    from unnest(coalesce(p_course_names, array[]::text[])) x
    where nullif(btrim(x), '') is not null
    group by lower(btrim(x))
  ) n;
  if coalesce(cardinality(v_names), 0) = 0 then
    raise exception 'COURSE_REQUIRED';
  end if;
  if jsonb_typeof(coalesce(p_payment_records, '[]'::jsonb)) <> 'array' then
    raise exception 'PAYMENT_RECORDS_INVALID';
