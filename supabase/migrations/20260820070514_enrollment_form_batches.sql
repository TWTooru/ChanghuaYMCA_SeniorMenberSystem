create or replace function private.enforce_billing_receipt_single_form()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_receipt_form_id bigint;
  v_course_form_id bigint;
begin
  select r.form_id into v_receipt_form_id
  from public.billing_receipts r
  where r.receipt_id = new.receipt_id
  for share;

  select c.form_id into v_course_form_id
  from public.courses c
  where c.course_id = new.course_id
  for share;

  if v_receipt_form_id is distinct from v_course_form_id then
    raise exception 'PAYMENT_FORM_MISMATCH';
  end if;

  return new;
end;
$$;

