    if v_amount < 0 then
      raise exception 'PAYMENT_AMOUNT_INVALID';
    end if;

    insert into public.billing_receipts (form_id, receipt_kind, amount, invoice_number)
    values (v_form_id, 'other', v_amount, nullif(btrim(v_payment ->> 'invoice_number'), ''))
    returning receipt_id into v_receipt;

    for v_course in select value #>> '{}' from jsonb_array_elements(v_payment -> 'course_names') loop
      if not exists (select 1 from unnest(v_names) n where lower(btrim(n)) = lower(btrim(v_course))) then
        raise exception 'PAYMENT_COURSE_NOT_SELECTED';
      end if;
      insert into public.billing_receipt_courses (receipt_id, course_id)
      select v_receipt, c.course_id
      from public.courses c
      where c.enrollment_id = v_enrollment_id
        and lower(btrim(c.course_name)) = lower(btrim(v_course));
    end loop;
  end loop;

  return v_enrollment_id;
end;
