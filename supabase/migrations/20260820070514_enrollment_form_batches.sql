    ) values (
      p_student_id, normalized_period, start_date_value, end_date_value,
      actor_user_id, actor_account
    ) returning enrollment_id into v_enrollment_id;
    v_appended := false;
  end if;

  v_form := private.create_enrollment_form_records(
    v_enrollment_id,
    p_enrollment,
    actor_user_id,
    actor_account
  );

  return pg_catalog.jsonb_build_object(
