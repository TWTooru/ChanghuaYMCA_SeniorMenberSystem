-- 8. Shared private form writers
create or replace function private.create_enrollment_form_records(
  p_enrollment_id bigint,
  p_form jsonb,
  p_actor_user_id uuid,
  p_actor_account text
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  normalized_courses text[];
  reported_on_text text;
  reported_on_value date;
  v_next_sequence integer;
  v_form_id bigint;
  v_prepaid_amount integer;
  v_tuition integer;
  v_materials integer;
  v_membership integer;
  v_formal_amount integer;
  v_prepaid_receipt_number text;
  v_fee_receipt_number text;
  v_prepaid_receipt_id bigint;
  v_formal_receipt_id bigint;
begin
  if p_form is null or pg_catalog.jsonb_typeof(p_form) <> 'object' then
    raise exception 'INVALID_ENROLLMENT_PAYLOAD';
  end if;

  if pg_catalog.jsonb_typeof(p_form -> 'courses') is distinct from 'array' then
    raise exception 'COURSE_REQUIRED';
  end if;
  if exists (
    select 1
    from pg_catalog.jsonb_array_elements(p_form -> 'courses') item(value)
    where pg_catalog.jsonb_typeof(item.value) <> 'string'
       or nullif(pg_catalog.btrim(item.value #>> '{}'), '') is null
  ) then
    raise exception 'COURSE_REQUIRED';
  end if;
  select pg_catalog.array_agg(course_name order by course_name)
  into normalized_courses
  from (
    select min(pg_catalog.btrim(item.value #>> '{}')) course_name
    from pg_catalog.jsonb_array_elements(p_form -> 'courses') item(value)
    group by pg_catalog.lower(pg_catalog.btrim(item.value #>> '{}'))
  ) normalized;
  if coalesce(pg_catalog.cardinality(normalized_courses), 0) = 0 then
    raise exception 'COURSE_REQUIRED';
  end if;

  if exists (
    select 1
    from public.courses c
    where c.enrollment_id = p_enrollment_id
      and pg_catalog.lower(c.course_name) = any(
        select pg_catalog.lower(nc) from pg_catalog.unnest(normalized_courses) nc
      )
  ) then
    raise exception 'COURSE_ALREADY_SELECTED';
  end if;

  v_prepaid_amount := private.optional_nonnegative_integer(p_form, 'prepaid_amount');
  v_tuition := private.optional_nonnegative_integer(p_form, 'tuition_fee');
  v_materials := private.optional_nonnegative_integer(p_form, 'materials_fee');
  v_membership := private.optional_nonnegative_integer(p_form, 'membership_fee');
  v_formal_amount := coalesce(v_tuition, 0) + coalesce(v_materials, 0) + coalesce(v_membership, 0);

  reported_on_text := nullif(pg_catalog.btrim(p_form ->> 'reported_on'), '');
  if reported_on_text is null then
    reported_on_text := nullif(pg_catalog.btrim(p_form ->> 'handled_on'), '');
  end if;

  if reported_on_text is not null then
    if reported_on_text !~ '^\d{4}-\d{2}-\d{2}$' then
      raise exception 'REPORTED_ON_INVALID';
    end if;
    begin
      reported_on_value := reported_on_text::date;
    exception when others then
      raise exception 'REPORTED_ON_INVALID';
    end;
    if pg_catalog.to_char(reported_on_value, 'YYYY-MM-DD') <> reported_on_text then
      raise exception 'REPORTED_ON_INVALID';
    end if;
  end if;

  select coalesce(max(form_sequence), 0) + 1
  into v_next_sequence
  from public.enrollment_forms
  where enrollment_id = p_enrollment_id;

  insert into public.enrollment_forms (
    enrollment_id,
    form_sequence,
    reg_type,
    tuition_fee,
    materials_fee,
    membership_fee,
    handled_by_name,
    handled_by_user_id,
    handled_by_account,
    reported_on,
    notes,
    refunded,
    refund_info
  ) values (
    p_enrollment_id,
    v_next_sequence,
    coalesce(nullif(pg_catalog.btrim(p_form ->> 'reg_type'), ''), '續'),
    v_tuition,
    v_materials,
    v_membership,
    nullif(pg_catalog.btrim(p_form ->> 'handled_by_name'), ''),
    p_actor_user_id,
    p_actor_account,
    reported_on_value,
    nullif(pg_catalog.btrim(p_form ->> 'notes'), ''),
    case when (p_form ->> 'refunded')::boolean is true or (p_form ->> 'refunded') = '1' then true else false end,
    nullif(pg_catalog.btrim(p_form ->> 'refund_info'), '')
  ) returning form_id into v_form_id;

  insert into public.courses (enrollment_id, form_id, course_name)
  select p_enrollment_id, v_form_id, course_name
  from pg_catalog.unnest(normalized_courses) selected(course_name);

  v_prepaid_receipt_number := nullif(pg_catalog.btrim(p_form ->> 'prepaid_receipt_number'), '');
  if coalesce(v_prepaid_amount, 0) > 0 or v_prepaid_receipt_number is not null then
    insert into public.billing_receipts (form_id, receipt_kind, amount, invoice_number)
    values (v_form_id, 'prepaid', coalesce(v_prepaid_amount, 0), v_prepaid_receipt_number)
    returning receipt_id into v_prepaid_receipt_id;

    insert into public.billing_receipt_courses (receipt_id, course_id)
    select v_prepaid_receipt_id, c.course_id
    from public.courses c
    where c.form_id = v_form_id;
  end if;

  v_fee_receipt_number := nullif(pg_catalog.btrim(p_form ->> 'fee_receipt_number'), '');
  if v_formal_amount > 0 or v_fee_receipt_number is not null then
    insert into public.billing_receipts (form_id, receipt_kind, amount, invoice_number)
    values (v_form_id, 'formal', v_formal_amount, v_fee_receipt_number)
    returning receipt_id into v_formal_receipt_id;

    insert into public.billing_receipt_courses (receipt_id, course_id)
    select v_formal_receipt_id, c.course_id
    from public.courses c
    where c.form_id = v_form_id;
  end if;

  return pg_catalog.jsonb_build_object(
    'form_id', v_form_id,
    'form_sequence', v_next_sequence
  );
end;
$$;

revoke all on function private.create_enrollment_form_records(bigint, jsonb, uuid, text)
from public, anon, authenticated;

create or replace function private.update_enrollment_form_records(
  p_form_id bigint,
  p_form jsonb,
  p_actor_user_id uuid,
  p_actor_account text
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_enrollment_id bigint;
  normalized_courses text[];
  reported_on_text text;
  reported_on_value date;
  v_prepaid_amount integer;
  v_tuition integer;
  v_materials integer;
  v_membership integer;
  v_formal_amount integer;
  v_prepaid_receipt_number text;
  v_fee_receipt_number text;
  v_prepaid_receipt_id bigint;
  v_formal_receipt_id bigint;
begin
  if p_form is null or pg_catalog.jsonb_typeof(p_form) <> 'object' then
    raise exception 'INVALID_ENROLLMENT_PAYLOAD';
  end if;

  select enrollment_id into v_enrollment_id
  from public.enrollment_forms
  where form_id = p_form_id
  for update;
  if not found then
    raise exception 'ENROLLMENT_FORM_NOT_FOUND';
  end if;

  if pg_catalog.jsonb_typeof(p_form -> 'courses') is distinct from 'array' then
    raise exception 'COURSE_REQUIRED';
  end if;
  if exists (
    select 1
    from pg_catalog.jsonb_array_elements(p_form -> 'courses') item(value)
    where pg_catalog.jsonb_typeof(item.value) <> 'string'
       or nullif(pg_catalog.btrim(item.value #>> '{}'), '') is null
  ) then
    raise exception 'COURSE_REQUIRED';
  end if;
  select pg_catalog.array_agg(course_name order by course_name)
  into normalized_courses
  from (
    select min(pg_catalog.btrim(item.value #>> '{}')) course_name
    from pg_catalog.jsonb_array_elements(p_form -> 'courses') item(value)
    group by pg_catalog.lower(pg_catalog.btrim(item.value #>> '{}'))
  ) normalized;
  if coalesce(pg_catalog.cardinality(normalized_courses), 0) = 0 then
    raise exception 'COURSE_REQUIRED';
  end if;

  if exists (
    select 1
    from public.courses c
    where c.enrollment_id = v_enrollment_id
      and c.form_id <> p_form_id
      and pg_catalog.lower(c.course_name) = any(
        select pg_catalog.lower(nc) from pg_catalog.unnest(normalized_courses) nc
      )
  ) then
    raise exception 'COURSE_ALREADY_SELECTED';
  end if;

  if exists (
    select 1
    from public.courses c
    join public.billing_receipt_courses link on link.course_id = c.course_id
    join public.billing_receipts r on r.receipt_id = link.receipt_id
    where c.form_id = p_form_id
      and r.receipt_kind = 'other'
      and not (pg_catalog.lower(c.course_name) = any(
        select pg_catalog.lower(nc) from pg_catalog.unnest(normalized_courses) nc
      ))
  ) then
    raise exception 'COURSE_RECEIPT_LOCKED';
  end if;

  delete from public.billing_receipt_courses link
  where link.receipt_id in (
    select r.receipt_id from public.billing_receipts r
    where r.form_id = p_form_id and r.receipt_kind in ('prepaid', 'formal')
  );

  delete from public.courses c
  where c.form_id = p_form_id
    and not (pg_catalog.lower(c.course_name) = any(
      select pg_catalog.lower(nc) from pg_catalog.unnest(normalized_courses) nc
    ));

  insert into public.courses (enrollment_id, form_id, course_name)
  select v_enrollment_id, p_form_id, nc
  from pg_catalog.unnest(normalized_courses) nc
  where not exists (
    select 1 from public.courses c
    where c.form_id = p_form_id and pg_catalog.lower(c.course_name) = pg_catalog.lower(nc)
  );

  v_prepaid_amount := private.optional_nonnegative_integer(p_form, 'prepaid_amount');
  v_tuition := private.optional_nonnegative_integer(p_form, 'tuition_fee');
  v_materials := private.optional_nonnegative_integer(p_form, 'materials_fee');
  v_membership := private.optional_nonnegative_integer(p_form, 'membership_fee');
  v_formal_amount := coalesce(v_tuition, 0) + coalesce(v_materials, 0) + coalesce(v_membership, 0);

  reported_on_text := nullif(pg_catalog.btrim(p_form ->> 'reported_on'), '');
  if reported_on_text is null then
    reported_on_text := nullif(pg_catalog.btrim(p_form ->> 'handled_on'), '');
  end if;

  if reported_on_text is not null then
    if reported_on_text !~ '^\d{4}-\d{2}-\d{2}$' then
      raise exception 'REPORTED_ON_INVALID';
    end if;
    begin
      reported_on_value := reported_on_text::date;
    exception when others then
      raise exception 'REPORTED_ON_INVALID';
    end;
    if pg_catalog.to_char(reported_on_value, 'YYYY-MM-DD') <> reported_on_text then
      raise exception 'REPORTED_ON_INVALID';
    end if;
  end if;

  v_prepaid_receipt_number := nullif(pg_catalog.btrim(p_form ->> 'prepaid_receipt_number'), '');
  if coalesce(v_prepaid_amount, 0) > 0 or v_prepaid_receipt_number is not null then
    insert into public.billing_receipts (form_id, receipt_kind, amount, invoice_number)
    values (p_form_id, 'prepaid', coalesce(v_prepaid_amount, 0), v_prepaid_receipt_number)
    on conflict (form_id, receipt_kind) where receipt_kind in ('prepaid', 'formal')
    do update set amount = excluded.amount, invoice_number = excluded.invoice_number, updated_at = now()
    returning receipt_id into v_prepaid_receipt_id;

    insert into public.billing_receipt_courses (receipt_id, course_id)
    select v_prepaid_receipt_id, c.course_id
    from public.courses c
    where c.form_id = p_form_id;
  else
    delete from public.billing_receipts
    where form_id = p_form_id and receipt_kind = 'prepaid';
  end if;

  v_fee_receipt_number := nullif(pg_catalog.btrim(p_form ->> 'fee_receipt_number'), '');
  if v_formal_amount > 0 or v_fee_receipt_number is not null then
    insert into public.billing_receipts (form_id, receipt_kind, amount, invoice_number)
    values (p_form_id, 'formal', v_formal_amount, v_fee_receipt_number)
    on conflict (form_id, receipt_kind) where receipt_kind in ('prepaid', 'formal')
    do update set amount = excluded.amount, invoice_number = excluded.invoice_number, updated_at = now()
    returning receipt_id into v_formal_receipt_id;

    insert into public.billing_receipt_courses (receipt_id, course_id)
    select v_formal_receipt_id, c.course_id
    from public.courses c
    where c.form_id = p_form_id;
  else
    delete from public.billing_receipts
    where form_id = p_form_id and receipt_kind = 'formal';
  end if;

  update public.enrollment_forms
  set reg_type = coalesce(nullif(pg_catalog.btrim(p_form ->> 'reg_type'), ''), reg_type),
      tuition_fee = v_tuition,
      materials_fee = v_materials,
      membership_fee = v_membership,
      handled_by_name = nullif(pg_catalog.btrim(p_form ->> 'handled_by_name'), ''),
      handled_by_user_id = p_actor_user_id,
      handled_by_account = p_actor_account,
      reported_on = reported_on_value,
      notes = nullif(pg_catalog.btrim(p_form ->> 'notes'), ''),
      updated_at = now()
  where form_id = p_form_id;

  return pg_catalog.jsonb_build_object(
    'form_id', p_form_id,
    'enrollment_id', v_enrollment_id
  );
end;
$$;

revoke all on function private.update_enrollment_form_records(bigint, jsonb, uuid, text)
from public, anon, authenticated;

-- 9. Public RPCs
create or replace function public.create_member_enrollment(
  p_student_id bigint,
  p_enrollment jsonb
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_user_id uuid;
  actor_account text;
  start_date_text text;
  end_date_text text;
  start_date_value date;
  end_date_value date;
  normalized_period text;
  v_existing_enrollment_id bigint;
  v_existing_start_date date;
  v_existing_end_date date;
  v_enrollment_id bigint;
  v_appended boolean;
  v_form jsonb;
begin
  if public.current_app_role() not in ('editor', 'admin') then
    raise exception 'ENROLLMENT_CREATE_FORBIDDEN' using errcode = '42501';
  end if;

  actor_user_id := (select auth.uid());
  actor_account := pg_catalog.lower(nullif(pg_catalog.btrim(auth.jwt() ->> 'email'), ''));
  if actor_user_id is null or actor_account is null then
    raise exception 'AUTH_ACCOUNT_REQUIRED' using errcode = '42501';
  end if;

  if not exists (select 1 from public.students s where s.student_id = p_student_id) then
    raise exception 'STUDENT_NOT_FOUND';
  end if;

  if p_enrollment is null or pg_catalog.jsonb_typeof(p_enrollment) <> 'object' then
    raise exception 'INVALID_ENROLLMENT_PAYLOAD';
  end if;

  normalized_period := pg_catalog.btrim(p_enrollment ->> 'period');
  if normalized_period is null or normalized_period !~ '^第[1-9][0-9]*期$' then
    raise exception 'PERIOD_INVALID';
  end if;

  start_date_text := nullif(pg_catalog.btrim(p_enrollment ->> 'period_start_date'), '');
  end_date_text := nullif(pg_catalog.btrim(p_enrollment ->> 'period_end_date'), '');
  if start_date_text is null or end_date_text is null then
    raise exception 'PERIOD_DATES_REQUIRED';
  end if;
  if start_date_text !~ '^\d{4}-\d{2}-\d{2}$'
     or end_date_text !~ '^\d{4}-\d{2}-\d{2}$' then
    raise exception 'PERIOD_DATE_INVALID';
  end if;
  begin
    start_date_value := start_date_text::date;
    end_date_value := end_date_text::date;
  exception when others then
    raise exception 'PERIOD_DATE_INVALID';
  end;
  if pg_catalog.to_char(start_date_value, 'YYYY-MM-DD') <> start_date_text
     or pg_catalog.to_char(end_date_value, 'YYYY-MM-DD') <> end_date_text then
    raise exception 'PERIOD_DATE_INVALID';
  end if;
  if end_date_value < start_date_value then
    raise exception 'PERIOD_DATE_ORDER_INVALID';
  end if;

  select e.enrollment_id, e.period_start_date, e.period_end_date
  into v_existing_enrollment_id, v_existing_start_date, v_existing_end_date
  from public.enrollments e
  where e.student_id = p_student_id and e.period = normalized_period
  for update;

  if v_existing_enrollment_id is not null then
    if v_existing_start_date is not null or v_existing_end_date is not null then
      if start_date_value is distinct from v_existing_start_date
         or end_date_value is distinct from v_existing_end_date then
        raise exception 'PERIOD_DATES_MISMATCH';
