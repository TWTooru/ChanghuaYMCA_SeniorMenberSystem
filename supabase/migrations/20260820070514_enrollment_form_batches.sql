    v_enrollment_id, 1, p_reg_type,
    case when p_refunded = 1 then true else false end,
    p_refund_info
  ) returning form_id into v_form_id;

  insert into public.courses (enrollment_id, form_id, course_name)
  select v_enrollment_id, v_form_id, name from unnest(v_names) name;

  for v_payment in select value from jsonb_array_elements(p_payment_records) loop
    if jsonb_typeof(v_payment) <> 'object'
       or jsonb_typeof(v_payment -> 'course_names') <> 'array'
       or jsonb_typeof(v_payment -> 'amount') <> 'number' then
      raise exception 'PAYMENT_RECORDS_INVALID';
    end if;
