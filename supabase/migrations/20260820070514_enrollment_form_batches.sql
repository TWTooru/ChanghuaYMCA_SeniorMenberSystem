-- 1. Create enrollment_forms table
create table public.enrollment_forms (
  form_id bigint generated by default as identity primary key,
  enrollment_id bigint not null references public.enrollments(enrollment_id) on delete cascade,
  form_sequence integer not null check (form_sequence > 0),
  reg_type text,
  tuition_fee integer check (tuition_fee is null or tuition_fee >= 0),
  materials_fee integer check (materials_fee is null or materials_fee >= 0),
  membership_fee integer check (membership_fee is null or membership_fee >= 0),
  handled_by_name text,
  handled_by_user_id uuid,
  handled_by_account text,
  reported_on date,
  notes text,
  refunded boolean not null default false,
  refund_info text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint enrollment_forms_enrollment_sequence_key unique (enrollment_id, form_sequence),
  constraint enrollment_forms_form_enrollment_key unique (form_id, enrollment_id)
);

create index enrollment_forms_enrollment_id_idx on public.enrollment_forms(enrollment_id);

create trigger enrollment_forms_set_updated_at
before update on public.enrollment_forms
for each row execute function public.set_updated_at();

-- 2. Backfill sequence 1 form per existing enrollment
insert into public.enrollment_forms (
  enrollment_id,
  form_sequence,
  reg_type,
  tuition_fee,
  materials_fee,
  membership_fee,
  handled_by_name,
  handled_by_user_id,
  handled_by_account,
  reported_on,
  notes,
  refunded,
  refund_info,
  created_at,
  updated_at
)
select
  e.enrollment_id,
  1,
  e.reg_type,
  e.tuition_fee,
  e.materials_fee,
  e.membership_fee,
  e.handled_by_name,
  e.handled_by_user_id,
  e.handled_by_account,
  e.handled_on,
  e.notes,
  case when e.refunded = 1 then true else false end,
  e.refund_info,
  e.created_at,
  e.updated_at
from public.enrollments e;

-- 3. Add courses.form_id, backfill, constraints and indexes
alter table public.courses add column form_id bigint;

update public.courses c
set form_id = ef.form_id
from public.enrollment_forms ef
where ef.enrollment_id = c.enrollment_id;

alter table public.courses alter column form_id set not null;

create index courses_form_enrollment_idx on public.courses(form_id, enrollment_id);

alter table public.courses
add constraint courses_form_enrollment_fkey
foreign key (form_id, enrollment_id)
references public.enrollment_forms(form_id, enrollment_id)
on delete cascade;

-- 4. Add billing_receipts.form_id and receipt_kind
alter table public.billing_receipts
add column form_id bigint,
add column receipt_kind text;

update public.billing_receipts r
set form_id = derived.form_id
from (
  select link.receipt_id, min(c.form_id) as form_id
  from public.billing_receipt_courses link
  join public.courses c on c.course_id = link.course_id
  group by link.receipt_id
  having count(distinct c.form_id) = 1
) derived
where r.receipt_id = derived.receipt_id;

-- Classify receipts as prepaid, formal, or other
update public.billing_receipts r
set receipt_kind = case
  when r.form_id is not null and e.enrollment_id is not null
       and (r.amount = e.prepaid_amount and coalesce(r.invoice_number, '') = coalesce(e.prepaid_receipt_number, ''))
       and not (r.amount = (coalesce(e.tuition_fee, 0) + coalesce(e.materials_fee, 0) + coalesce(e.membership_fee, 0)) and coalesce(r.invoice_number, '') = coalesce(e.fee_receipt_number, ''))
    then 'prepaid'
  when r.form_id is not null and e.enrollment_id is not null
       and (r.amount = (coalesce(e.tuition_fee, 0) + coalesce(e.materials_fee, 0) + coalesce(e.membership_fee, 0)) and coalesce(r.invoice_number, '') = coalesce(e.fee_receipt_number, ''))
       and not (r.amount = e.prepaid_amount and coalesce(r.invoice_number, '') = coalesce(e.prepaid_receipt_number, ''))
    then 'formal'
  else 'other'
end
from public.enrollment_forms ef
join public.enrollments e on e.enrollment_id = ef.enrollment_id
where r.form_id = ef.form_id;

-- Ensure all receipts have form_id and receipt_kind
update public.billing_receipts
set receipt_kind = 'other'
where receipt_kind is null;

alter table public.billing_receipts
alter column form_id set not null,
alter column receipt_kind set not null;

alter table public.billing_receipts
add constraint billing_receipts_receipt_kind_check
check (receipt_kind in ('prepaid', 'formal', 'other'));

alter table public.billing_receipts
add constraint billing_receipts_form_id_fkey
foreign key (form_id) references public.enrollment_forms(form_id) on delete cascade;

create index billing_receipts_form_id_idx on public.billing_receipts(form_id);

create unique index billing_receipts_one_typed_kind_per_form_uidx
on public.billing_receipts(form_id, receipt_kind)
where receipt_kind in ('prepaid', 'formal');

