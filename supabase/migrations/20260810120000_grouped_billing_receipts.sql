  set amount = p_amount,
      invoice_number = nullif(pg_catalog.btrim(p_invoice_number), '')
  where receipt.receipt_id = p_receipt_id;

  select pg_catalog.array_agg(link.course_id order by link.course_id)
  into v_course_ids
  from public.billing_receipt_courses link
  where link.receipt_id = p_receipt_id;

  return pg_catalog.jsonb_build_object(
    'receipt_id', p_receipt_id,
    'course_ids', pg_catalog.to_jsonb(v_course_ids),
    'amount', p_amount,
    'invoice_number', nullif(pg_catalog.btrim(p_invoice_number), '')
  );
end;
$$;

