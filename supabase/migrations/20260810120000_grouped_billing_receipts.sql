create or replace function public.update_enrollment_with_courses(
  p_enrollment_id text,
  p_season text,
  p_reg_type text,
  p_pre_test text,
  p_post_test text,
  p_refunded integer,
  p_refund_info text,
  p_course_names text[]
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_names text[];
begin
  if public.current_app_role() not in ('editor', 'admin') then
    raise exception 'ENROLLMENT_UPDATE_FORBIDDEN' using errcode = '42501';
  end if;

  perform 1 from public.enrollments e
  where e.enrollment_id::text = p_enrollment_id for update;
  if not found then raise exception 'ENROLLMENT_NOT_FOUND'; end if;

  select pg_catalog.array_agg(name order by name) into v_names
  from (
    select min(pg_catalog.btrim(input.course_name)) as name
    from pg_catalog.unnest(coalesce(p_course_names, array[]::text[])) as input(course_name)
    where pg_catalog.btrim(input.course_name) <> ''
    group by pg_catalog.lower(pg_catalog.btrim(input.course_name))
  ) normalized;
  if coalesce(pg_catalog.cardinality(v_names), 0) = 0 then
    raise exception 'COURSE_REQUIRED';
  end if;

  if exists (
    select 1
    from public.courses c
    join public.billing_receipt_courses link on link.course_id = c.course_id
    where c.enrollment_id::text = p_enrollment_id
      and not exists (
        select 1
        from pg_catalog.unnest(v_names) as selected(course_name)
        where pg_catalog.lower(pg_catalog.btrim(selected.course_name)) =
              pg_catalog.lower(pg_catalog.btrim(c.course_name))
      )
  ) then
    raise exception 'COURSE_RECEIPT_LOCKED';
  end if;

  update public.enrollments e
  set season = p_season, reg_type = p_reg_type, pre_test = p_pre_test,
      post_test = p_post_test, refunded = p_refunded, refund_info = p_refund_info
  where e.enrollment_id::text = p_enrollment_id;

  delete from public.courses c
  where c.enrollment_id::text = p_enrollment_id
    and not exists (
      select 1 from pg_catalog.unnest(v_names) as selected(course_name)
      where pg_catalog.lower(selected.course_name) =
            pg_catalog.lower(pg_catalog.btrim(c.course_name))
    )
    and not exists (
      select 1 from public.billing_receipt_courses link
      where link.course_id = c.course_id
    );

  insert into public.courses (enrollment_id, course_name)
  select e.enrollment_id, selected.course_name
  from public.enrollments e
  cross join pg_catalog.unnest(v_names) as selected(course_name)
  where e.enrollment_id::text = p_enrollment_id
    and not exists (
      select 1 from public.courses c
      where c.enrollment_id = e.enrollment_id
        and pg_catalog.lower(pg_catalog.btrim(c.course_name)) =
            pg_catalog.lower(selected.course_name)
    );
end;
$$;

