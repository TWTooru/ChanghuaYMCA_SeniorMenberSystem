create or replace function private.prevent_grouped_receipt_cross_enrollment()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.enrollment_id is distinct from old.enrollment_id
     and exists (
       select 1
       from public.billing_receipt_courses moved_link
       join public.billing_receipt_courses sibling_link
         on sibling_link.receipt_id = moved_link.receipt_id
        and sibling_link.course_id <> moved_link.course_id
       join public.courses sibling
         on sibling.course_id = sibling_link.course_id
       where moved_link.course_id = old.course_id
         and sibling.enrollment_id is distinct from new.enrollment_id
     ) then
    raise exception 'PAYMENT_CROSS_ENROLLMENT';
  end if;
  return new;
end;
$$;

